-- Additive migration for the current RealEase EF Core schema (users and bigint properties).
-- Existing listings remain rentals; update their listing_type when they are actually for sale.
ALTER TABLE public.properties
    ADD COLUMN IF NOT EXISTS city text,
    ADD COLUMN IF NOT EXISTS listing_type text NOT NULL DEFAULT 'rent',
    ADD COLUMN IF NOT EXISTS sale_price numeric(12, 2);

ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS service_area text;

CREATE TABLE IF NOT EXISTS public.agent_inquiries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL,
    phone_number text NOT NULL,
    location text NOT NULL,
    intent text NOT NULL CHECK (intent IN ('rent', 'sell')),
    message text,
    property_id bigint REFERENCES public.properties(id) ON DELETE SET NULL,
    agent_id uuid REFERENCES public.users(id) ON DELETE SET NULL,
    status text NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ix_agent_inquiries_agent_id_created_at
    ON public.agent_inquiries (agent_id, created_at);
